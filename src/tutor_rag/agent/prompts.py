MEMORY_PROMPT_HEADER = "你可以使用长期记忆来更好地帮助学生。"
MEMORY_INDEX_HEADER = "当前已有的长期记忆（名称（类别）：描述）："
MEMORY_RULES = (
    "使用规则：\n"
    "1. 当索引中有与当前问题相关的记忆时，先调用 memory_read 查看完整内容再回答；\n"
    "2. 当学生透露重要个人信息、讲解偏好、错题或薄弱知识点时，主动调用 memory_write 记录；\n"
    "3. 错题与薄弱知识点用 append 逐条累积；更新学生画像或讲解偏好时先 memory_read，再用 replace 整理重写；\n"
    "4. 不要记录寒暄、闲聊等与学习无关的琐事。"
)
MEMORY_EMPTY_TEXT = (
    "你可以使用长期记忆来更好地帮助学生。目前还没有任何记忆。\n"
    "当学生透露重要个人信息、讲解偏好、错题或薄弱知识点时，主动调用 memory_write 记录。"
)


def memory_prompt_section(index: str) -> str:
    if not index:
        return MEMORY_EMPTY_TEXT
    return (
        f"{MEMORY_PROMPT_HEADER}\n{MEMORY_INDEX_HEADER}\n{index}\n\n{MEMORY_RULES}"
    )
