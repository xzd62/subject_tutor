def render_doc(stem: str, doc: dict[str, Any]) -> str:
    lines = [f"# {doc['title']}", ""]
    for chapter, sections in doc["chapters"]:
        lines.append(f"## {chapter}")
        lines.append("")
        for title, body in sections:
            supplement = SUPPLEMENTS.get(f"{stem}|{chapter}|{title}")
            if supplement and len(body) < 100:
                body = body + supplement
            lines.append(f"### {title}")
            lines.append("")
            lines.append(body)
            lines.append("")
    return "\n".join(lines).strip() + "\n"
